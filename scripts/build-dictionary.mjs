// Builds the game dictionary from the `word-list` package: lowercase words of 3–8 letters,
// written as a TS module so the client can lazy-load it and the server can import it.
import { readFileSync, writeFileSync } from 'node:fs'
import wordListPath from 'word-list'

const words = readFileSync(wordListPath, 'utf8')
	.split('\n')
	.filter((w) => /^[a-z]{3,8}$/.test(w))

const out = new URL('../src/game/dictionary.generated.ts', import.meta.url)
writeFileSync(
	out,
	`// Generated by scripts/build-dictionary.mjs. Do not edit.\nexport const WORDS = ${JSON.stringify(words.join('\n'))}\n`,
)
console.log(`Wrote ${words.length} words`)
